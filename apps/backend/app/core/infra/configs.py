"""
JARV Backend - Infrastructure configuration: generate, validate, cost, scale

- Nginx: a production server block for a domain (HTTP->HTTPS redirect with the
  ACME challenge path, TLS 1.2/1.3, security headers, request limits, proxy
  and WebSocket headers) for the given routes.
- Compose: a docker-compose file for the workspace's detected stack (web/API
  service, plus PostgreSQL and Redis when the project uses them), with
  health checks, env_file and named volumes. Secrets are referenced as
  ${VARS}, never written.
- Validation: compose, nginx, Dockerfile and .env.example checks (privileged
  containers, writable Docker socket, inline secrets, :latest images, root
  users, missing TLS files, variables used but not documented).
- Cost: configured fixed costs, recorded resources, and model spend, against
  the monthly budget.
- Scaling: replicas within the approved budget and replica limit are applied;
  anything beyond pauses for Richard (spending over budget is a hard boundary).
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
from uuid import UUID

import yaml
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import settings

_DOMAIN = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
_UPSTREAM = re.compile(r"^[a-zA-Z0-9._-]{1,63}:\d{2,5}$")
_PATH = re.compile(r"^/[A-Za-z0-9._~/-]*$")
_SECRET_KEY = re.compile(r"(password|secret|token|api[_-]?key|private[_-]?key)", re.I)
_SECRET_VALUE = re.compile(r"^(sk-|sk_live_|sk_test_|ghp_|xox[bp]-|AKIA)[A-Za-z0-9_-]{8,}|^[A-Za-z0-9+/=_-]{32,}$")


# ----- nginx ------------------------------------------------------------------------------------

def generate_nginx(domain: str, routes: Dict[str, str], *, websocket_paths: Optional[List[str]] = None,
                   max_body_mb: int = 20, rate_per_second: int = 10) -> str:
    domain = domain.strip().lower()
    if not _DOMAIN.match(domain):
        raise ValueError(f"'{domain}' is not a valid domain name")
    if not routes:
        raise ValueError("Give at least one route, e.g. {\"/\": \"web:3000\"}")
    for path, upstream in routes.items():
        if not _PATH.match(path):
            raise ValueError(f"'{path}' is not a valid location path")
        if not _UPSTREAM.match(upstream):
            raise ValueError(f"'{upstream}' must be service:port")
    zone = re.sub(r"[^a-z0-9]", "_", domain)[:40]
    ws = set(websocket_paths or [])
    unrouted = sorted(ws - set(routes))
    if unrouted:
        raise ValueError(f"WebSocket path(s) {', '.join(unrouted)} must also be routes")
    locations = []
    for path in sorted(routes, key=len, reverse=True):
        upgrade = ("        proxy_http_version 1.1;\n        proxy_set_header Upgrade $http_upgrade;\n"
                   "        proxy_set_header Connection \"upgrade\";\n        proxy_read_timeout 3600s;\n") if path in ws else ""
        locations.append(
            f"    location {path} {{\n"
            f"        limit_req zone={zone} burst={rate_per_second * 2} nodelay;\n"
            f"        proxy_pass http://{routes[path]};\n"
            "        proxy_set_header Host $host;\n"
            "        proxy_set_header X-Real-IP $remote_addr;\n"
            "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
            "        proxy_set_header X-Forwarded-Proto $scheme;\n"
            f"{upgrade}"
            "    }\n")
    return (
        f"# Generated by JARV for {domain}. Include from the http block (conf.d).\n"
        f"limit_req_zone $binary_remote_addr zone={zone}:10m rate={rate_per_second}r/s;\n\n"
        "server {\n    listen 80;\n    listen [::]:80;\n"
        f"    server_name {domain};\n\n"
        "    location /.well-known/acme-challenge/ {\n        root /var/www/certbot;\n    }\n\n"
        "    location / {\n        return 301 https://$host$request_uri;\n    }\n}\n\n"
        "server {\n    listen 443 ssl http2;\n    listen [::]:443 ssl http2;\n"
        f"    server_name {domain};\n\n"
        f"    ssl_certificate /etc/letsencrypt/live/{domain}/fullchain.pem;\n"
        f"    ssl_certificate_key /etc/letsencrypt/live/{domain}/privkey.pem;\n"
        "    ssl_protocols TLSv1.2 TLSv1.3;\n    ssl_prefer_server_ciphers on;\n"
        "    ssl_session_cache shared:SSL:10m;\n\n"
        "    add_header Strict-Transport-Security \"max-age=31536000; includeSubDomains\" always;\n"
        "    add_header X-Content-Type-Options nosniff always;\n"
        "    add_header X-Frame-Options DENY always;\n"
        "    add_header Referrer-Policy strict-origin-when-cross-origin always;\n\n"
        f"    client_max_body_size {max_body_mb}m;\n    server_tokens off;\n\n"
        + "\n".join(locations) + "}\n")


def check_nginx(text: str) -> List[Dict[str, str]]:
    issues: List[Dict[str, str]] = []
    body = re.sub(r"#[^\n]*", "", text)
    if body.count("{") != body.count("}"):
        issues.append({"severity": "error", "issue": "unbalanced braces"})
    servers = re.findall(r"server\s*\{", body)
    if not servers:
        issues.append({"severity": "error", "issue": "no server block"})
    if "listen 443" in body and "ssl_certificate " not in body:
        issues.append({"severity": "error", "issue": "listens on 443 without ssl_certificate"})
    if "listen 443" not in body:
        issues.append({"severity": "warning", "issue": "no HTTPS server (listen 443)"})
    if "server_name" not in body:
        issues.append({"severity": "warning", "issue": "no server_name"})
    if "Strict-Transport-Security" not in body and "listen 443" in body:
        issues.append({"severity": "warning", "issue": "no HSTS header"})
    if "server_tokens off" not in body:
        issues.append({"severity": "info", "issue": "server_tokens not turned off"})
    if re.search(r"ssl_protocols[^;]*(SSLv3|TLSv1(\s|;)|TLSv1\.1)", body):
        issues.append({"severity": "error", "issue": "outdated TLS protocols enabled"})
    return issues


# ----- docker compose ----------------------------------------------------------------------------

def _deps(root: Path) -> str:
    blob = ""
    for name in ("package.json", "requirements.txt", "pyproject.toml"):
        path = root / name
        if path.is_file():
            blob += path.read_text(encoding="utf-8", errors="ignore").lower()
    return blob


def _fastapi_module(root: Path) -> Optional[str]:
    for path in sorted(root.rglob("*.py"))[:400]:
        if any(p in ("node_modules", ".venv", "venv", "tests", ".git") for p in path.parts):
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        match = re.search(r"^(\w+)\s*=\s*FastAPI\(", text, re.M)
        if match:
            module = ".".join(path.relative_to(root).with_suffix("").parts)
            return f"{module}:{match.group(1)}"
    return None


def generate_compose(root: Path, detected: Dict[str, Any], app_name: str) -> Tuple[str, List[str]]:
    stack = set(detected.get("stack") or [])
    commands = detected.get("commands") or {}
    deps = _deps(root)
    notes: List[str] = []
    services: Dict[str, Any] = {}
    volumes: Dict[str, Any] = {}
    needs_db = any(k in deps for k in ("psycopg", "asyncpg", "\"pg\"", "prisma", "sqlalchemy", "postgres", "typeorm"))
    needs_redis = any(k in deps for k in ("redis", "ioredis", "bullmq", "celery"))
    depends = []
    if needs_db:
        depends.append("postgres")
    if needs_redis:
        depends.append("redis")
    if not (root / "Dockerfile").is_file():
        notes.append("No Dockerfile in the project: the app service needs one to build.")
    if "node" in stack:
        port = 3000
        services["web"] = {
            "build": ".", "restart": "unless-stopped", "env_file": [".env"], "ports": [f"{port}:{port}"],
            "command": commands.get("start") or ("npm run start" if "nextjs" in stack else "node index.js"),
            "healthcheck": {"test": ["CMD-SHELL", f"wget -qO- http://localhost:{port}/ >/dev/null || exit 1"],
                            "interval": "30s", "timeout": "5s", "retries": 3}}
    if "python" in stack:
        module = _fastapi_module(root) if "fastapi" in stack else None
        port = 8000
        if "fastapi" in stack and not module:
            notes.append("FastAPI app object not found: set the uvicorn module in the api command.")
        command = f"uvicorn {module} --host 0.0.0.0 --port {port}" if module else (
            "gunicorn wsgi:application --bind 0.0.0.0:8000" if "django" in stack else
            f"python -m {re.sub(r'[^a-z0-9_]', '_', app_name.lower())}")
        services["api"] = {
            "build": ".", "restart": "unless-stopped", "env_file": [".env"], "ports": [f"{port}:{port}"],
            "command": command,
            "healthcheck": {"test": ["CMD-SHELL", f"python -c \"import urllib.request;urllib.request.urlopen('http://localhost:{port}/')\" || exit 1"],
                            "interval": "30s", "timeout": "5s", "retries": 3}}
    if not services:
        raise ValueError("No web or API stack was detected to put in a compose file")
    for svc in services.values():
        if depends:
            svc["depends_on"] = {d: {"condition": "service_healthy"} for d in depends}
    if needs_db:
        services["postgres"] = {
            "image": "postgres:16-alpine", "restart": "unless-stopped",
            "environment": {"POSTGRES_DB": "${POSTGRES_DB}", "POSTGRES_USER": "${POSTGRES_USER}",
                            "POSTGRES_PASSWORD": "${POSTGRES_PASSWORD}"},
            "volumes": ["postgres_data:/var/lib/postgresql/data"],
            "healthcheck": {"test": ["CMD-SHELL", "pg_isready -U $${POSTGRES_USER}"], "interval": "10s",
                            "timeout": "5s", "retries": 5}}
        volumes["postgres_data"] = {}
        notes.append("Set POSTGRES_DB, POSTGRES_USER and POSTGRES_PASSWORD in .env (never commit it).")
    if needs_redis:
        services["redis"] = {"image": "redis:7-alpine", "restart": "unless-stopped",
                             "command": "redis-server --appendonly yes", "volumes": ["redis_data:/data"],
                             "healthcheck": {"test": ["CMD", "redis-cli", "ping"], "interval": "10s",
                                             "timeout": "5s", "retries": 5}}
        volumes["redis_data"] = {}
    doc: Dict[str, Any] = {"name": re.sub(r"[^a-z0-9-]", "-", app_name.lower()).strip("-") or "app",
                           "services": services}
    if volumes:
        doc["volumes"] = volumes
    text = "# Generated by JARV from the detected stack. Secrets come from .env, never this file.\n" + \
        yaml.safe_dump(doc, sort_keys=False, default_flow_style=False)
    return text, notes


def check_compose(text: str, documented: Optional[set] = None) -> List[Dict[str, str]]:
    issues: List[Dict[str, str]] = []
    try:
        data = yaml.safe_load(text) or {}
    except yaml.YAMLError as exc:
        return [{"severity": "error", "issue": f"invalid YAML: {str(exc)[:200]}"}]
    services = data.get("services") if isinstance(data, dict) else None
    if not isinstance(services, dict) or not services:
        return [{"severity": "error", "issue": "no services"}]
    for name, svc in services.items():
        svc = svc or {}
        where = f"service {name}"
        if not svc.get("image") and not svc.get("build"):
            issues.append({"severity": "error", "issue": f"{where}: neither image nor build"})
        image = str(svc.get("image") or "")
        if image and (image.endswith(":latest") or ":" not in image.split("/")[-1]):
            issues.append({"severity": "warning", "issue": f"{where}: image '{image}' is not pinned to a version"})
        if svc.get("privileged"):
            issues.append({"severity": "error", "issue": f"{where}: privileged container"})
        for volume in svc.get("volumes") or []:
            text_volume = volume if isinstance(volume, str) else str(volume.get("source", "")) + ":" + str(volume.get("target", ""))
            if "docker.sock" in text_volume and not text_volume.endswith(":ro"):
                issues.append({"severity": "error", "issue": f"{where}: Docker socket mounted writable"})
        env = svc.get("environment") or {}
        pairs = env.items() if isinstance(env, dict) else [(e.split("=", 1) + [""])[:2] for e in env]
        for key, value in pairs:
            value = str(value or "")
            if _SECRET_KEY.search(str(key)) and value and not value.startswith("${") and _SECRET_VALUE.search(value):
                issues.append({"severity": "error", "issue": f"{where}: {key} has an inline secret value"})
        if svc.get("network_mode") == "host":
            issues.append({"severity": "warning", "issue": f"{where}: host networking"})
        if not svc.get("restart") and not (svc.get("deploy") or {}).get("restart_policy"):
            issues.append({"severity": "info", "issue": f"{where}: no restart policy"})
        if not svc.get("healthcheck") and svc.get("build"):
            issues.append({"severity": "info", "issue": f"{where}: no healthcheck"})
    if documented is not None:
        used = set(re.findall(r"\$\{([A-Z][A-Z0-9_]*)(?::?-[^}]*)?\}", text))
        missing = sorted(v for v in used if v not in documented)
        if missing:
            issues.append({"severity": "warning", "issue": f"variables used but not in .env.example: {', '.join(missing)}"})
    return issues


def check_dockerfile(text: str) -> List[Dict[str, str]]:
    issues: List[Dict[str, str]] = []
    froms = re.findall(r"^\s*FROM\s+(\S+)", text, re.M | re.I)
    if not froms:
        issues.append({"severity": "error", "issue": "no FROM"})
    for image in froms:
        if image.lower() != "scratch" and (image.endswith(":latest") or ":" not in image.split("/")[-1]) and "$" not in image:
            issues.append({"severity": "warning", "issue": f"base image '{image}' is not pinned"})
    if not re.search(r"^\s*USER\s+(?!root\b)\S+", text, re.M | re.I):
        issues.append({"severity": "warning", "issue": "runs as root (no USER)"})
    if re.search(r"^\s*(ENV|ARG)\s+\S*(PASSWORD|SECRET|TOKEN|API_KEY)\S*[ =]\S+", text, re.M | re.I):
        issues.append({"severity": "error", "issue": "secret set in the image (ENV/ARG)"})
    if re.search(r"curl[^|\n]*\|\s*(ba)?sh", text):
        issues.append({"severity": "warning", "issue": "pipes a download into a shell"})
    return issues


def documented_vars(root: Path) -> Optional[set]:
    for name in (".env.example", ".env.sample", "env.example", ".env.production.example"):
        path = root / name
        if path.is_file():
            return {line.split("=", 1)[0].strip() for line in path.read_text(encoding="utf-8", errors="ignore").splitlines()
                    if "=" in line and not line.strip().startswith("#")}
    return None


def validate_folder(root: Path) -> Dict[str, Any]:
    documented = documented_vars(root)
    files: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(root.rglob("*")):
        if any(p in ("node_modules", ".git", ".venv", "venv", "dist", "build") for p in path.parts) or not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        name = path.name.lower()
        try:
            if re.match(r"^(docker-)?compose[\w.-]*\.ya?ml$", name):
                files[rel] = check_compose(path.read_text(encoding="utf-8", errors="ignore"), documented)
            elif name == "dockerfile" or name.startswith("dockerfile."):
                files[rel] = check_dockerfile(path.read_text(encoding="utf-8", errors="ignore"))
            elif name.endswith(".conf") and ("nginx" in rel.lower()):
                files[rel] = check_nginx(path.read_text(encoding="utf-8", errors="ignore"))
        except OSError as exc:
            files[rel] = [{"severity": "error", "issue": f"unreadable: {exc}"}]
        if len(files) >= 60:
            break
    if documented is None and any(rel.endswith((".yml", ".yaml")) for rel in files):
        files[".env.example"] = [{"severity": "warning", "issue": "missing: document the settings the stack needs"}]
    errors = sum(1 for issues in files.values() for i in issues if i["severity"] == "error")
    warnings = sum(1 for issues in files.values() for i in issues if i["severity"] == "warning")
    return {"files": files, "errors": errors, "warnings": warnings, "valid": errors == 0 and bool(files)}


# ----- cost -------------------------------------------------------------------------------------

def fixed_costs() -> Dict[str, float]:
    raw = getattr(settings, "INFRA_FIXED_COSTS", "") or ""
    try:
        data = json.loads(raw) if raw else {}
        return {str(k): float(v) for k, v in data.items()}
    except (ValueError, TypeError, AttributeError):
        raise ValueError("INFRA_FIXED_COSTS must be JSON like {\"vps\": 24, \"domain\": 1.2}") from None


async def estimate_monthly(db: AsyncSession, workspace_id: Optional[UUID]) -> Dict[str, Any]:
    from app.core.swarm.tracking import estimate_cost
    from app.models.operations import InfrastructureResource
    from app.models.swarm import SwarmCostRecord, SwarmRun
    from app.models.task import Task

    items: List[Dict[str, Any]] = [{"item": k, "monthly": round(v, 2), "source": "INFRA_FIXED_COSTS"}
                                   for k, v in fixed_costs().items()]
    query = select(InfrastructureResource).where(InfrastructureResource.is_active.is_(True))
    if workspace_id is not None:
        query = query.where((InfrastructureResource.workspace_id == workspace_id) |
                            (InfrastructureResource.workspace_id.is_(None)))
    for r in (await db.execute(query)).scalars().all():
        monthly = float(r.monthly_cost or 0) or float(r.hourly_cost or 0) * 730
        if monthly:
            items.append({"item": f"{r.resource_type}: {r.resource_name}", "monthly": round(monthly, 2),
                          "source": "recorded resource"})
    since = datetime.now(timezone.utc) - timedelta(days=30)
    swarm_query = select(func.coalesce(func.sum(SwarmCostRecord.total_cost), 0)).join(
        SwarmRun, SwarmCostRecord.swarm_run_id == SwarmRun.id).where(SwarmCostRecord.created_at >= since)
    task_query = select(func.coalesce(func.sum(Task.tokens_used), 0)).where(Task.updated_at >= since)
    if workspace_id is not None:
        swarm_query = swarm_query.where(SwarmRun.workspace_id == workspace_id)
        task_query = task_query.where(Task.workspace_id == workspace_id)
    swarm_cost = float((await db.execute(swarm_query)).scalar_one() or 0)
    tokens = int((await db.execute(task_query)).scalar_one() or 0)
    model_cost = estimate_cost(getattr(settings, "DEFAULT_MODEL", None) or "claude-sonnet-4-6", tokens)
    if swarm_cost or model_cost:
        items.append({"item": "AI model usage (last 30 days)", "monthly": round(swarm_cost + model_cost, 2),
                      "source": f"{tokens} task tokens + swarm records (estimated)"})
    total = round(sum(i["monthly"] for i in items), 2)
    budget = float(getattr(settings, "INFRA_MONTHLY_BUDGET", 0) or 0)
    return {"items": items, "monthly_total": total, "currency": "USD", "budget": budget or None,
            "remaining": round(budget - total, 2) if budget else None,
            "within_budget": (total <= budget) if budget else None,
            "notes": [] if items else ["No costs configured: set INFRA_FIXED_COSTS (e.g. your VPS plan) and "
                                       "INFRA_MONTHLY_BUDGET."]}


def scaling_decision(current_monthly: float, current_replicas: int, replicas: int) -> Dict[str, Any]:
    per_replica = float(getattr(settings, "INFRA_REPLICA_MONTHLY_COST", 0) or 0)
    max_replicas = int(getattr(settings, "INFRA_MAX_REPLICAS", 5) or 5)
    budget = float(getattr(settings, "INFRA_MONTHLY_BUDGET", 0) or 0)
    delta = round(max(0, replicas - current_replicas) * per_replica, 2)
    projected = round(current_monthly + delta, 2)
    reasons = []
    if replicas > max_replicas:
        reasons.append(f"{replicas} replicas is above the limit of {max_replicas} (INFRA_MAX_REPLICAS)")
    if delta > 0 and not budget:
        reasons.append(f"adds about ${delta:.2f}/month and no monthly budget is approved (INFRA_MONTHLY_BUDGET)")
    elif delta > 0 and projected > budget:
        reasons.append(f"projected ${projected:.2f}/month exceeds the approved budget of ${budget:.2f}")
    return {"current_replicas": current_replicas, "replicas": replicas, "added_monthly_cost": delta,
            "projected_monthly": projected, "budget": budget or None, "needs_approval": bool(reasons),
            "reasons": reasons}
